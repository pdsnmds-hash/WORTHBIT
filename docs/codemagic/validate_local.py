"""Exercise signing helpers with disposable files; never create a production key."""
import os
from pathlib import Path
import subprocess
import tempfile
import zipfile
import yaml

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / 'docs/codemagic'
JAVA = Path(os.environ['JAVA_HOME']) / 'bin'


def run(args, env=None, ok=True):
    result = subprocess.run([str(a) for a in args], env=env, capture_output=True, text=True)
    if (result.returncode == 0) != ok:
        raise AssertionError('Unexpected command result: ' + str(args[0]) + '\n' + result.stdout + result.stderr)
    return result


def main():
    for file in [ROOT / 'codemagic.yaml', SCRIPTS / 'codemagic.yaml', SCRIPTS / 'generate-upload-key.yaml']:
        config = yaml.safe_load(file.read_text())
        for workflow in config['workflows'].values():
            for script in workflow['scripts']:
                subprocess.run(['bash', '-n'], input=script['script'], text=True, check=True)
    with tempfile.TemporaryDirectory(prefix='worthbit-ci-') as folder:
        tmp = Path(folder)
        env = os.environ.copy()
        env.update(CM_BUILD_DIR=str(tmp), CM_KEYSTORE_PATH=str(tmp / 'test.jks'),
                   CM_KEYSTORE_PASSWORD=' test:=#!\\é', CM_KEY_PASSWORD=' test:=#!\\é', CM_KEY_ALIAS='test')
        run([JAVA / 'keytool', '-genkeypair', '-noprompt', '-storetype', 'JKS', '-keyalg', 'RSA', '-keysize', '2048',
             '-validity', '1', '-dname', 'CN=Disposable test', '-keystore', env['CM_KEYSTORE_PATH'],
             '-alias', 'test', '-storepass:env', 'CM_KEYSTORE_PASSWORD', '-keypass:env', 'CM_KEY_PASSWORD'], env)
        missing = env.copy(); del missing['CM_KEY_ALIAS']
        run(['python3', SCRIPTS / 'prepare_signing.py'], missing, ok=False)
        run(['python3', SCRIPTS / 'prepare_signing.py'], env)
        assert (tmp / 'release/signing/upload-keystore.jks').stat().st_mode & 0o777 == 0o600
        assert (tmp / 'release/upload-key.properties').stat().st_mode & 0o777 == 0o600
        run(['python3', SCRIPTS / 'prepare_signing.py'], env, ok=False)
        source = tmp / 'ReadProperties.java'
        source.write_text('import java.util.*; import java.io.*; public class ReadProperties { public static void main(String[] a) throws Exception { Properties p=new Properties(); try(var s=new FileInputStream(a[0])){p.load(s);} if(!p.getProperty("storePassword").equals(System.getenv("CM_KEYSTORE_PASSWORD"))) throw new RuntimeException("round trip"); }}')
        run([JAVA / 'java', source, tmp / 'release/upload-key.properties'], env)
        sdk = tmp / 'sdk'
        for name, rev in [('latest', '10.0'), ('latest-2', '19.0')]:
            tool = sdk / 'cmdline-tools' / name / 'bin/sdkmanager'
            tool.parent.mkdir(parents=True)
            tool.parent.parent.joinpath('source.properties').write_text('Pkg.Revision=' + rev)
            tool.write_text('#!/bin/sh\nprintf "%s\\n" "$@" > "$CM_BUILD_DIR/sdk-args"\n')
            tool.chmod(0o700)
        env['ANDROID_SDK_ROOT'] = str(sdk)
        result = run(['python3', SCRIPTS / 'configure_sdk.py'], env)
        assert 'latest-2' in result.stdout
        assert (tmp / 'sdk-args').read_text().splitlines() == ['--sdk_root=' + str(sdk), 'platforms;android-36', 'build-tools;35.0.0']
        run(['python3', SCRIPTS / 'configure_sdk.py'], env, ok=False)
        for mode in ['universal', 'four-abi', 'unsigned', 'partial', 'private', 'provenance']:
            bundle = tmp / (mode + '.aab')
            with zipfile.ZipFile(bundle, 'w') as archive:
                archive.writestr('base/dex/classes.dex', b'test fixture')
                if mode in {'four-abi', 'partial'}:
                    for abi in (['arm64-v8a'] if mode == 'partial' else ['armeabi-v7a', 'arm64-v8a', 'x86', 'x86_64']):
                        archive.writestr('base/lib/' + abi + '/libfixture.so', b'test fixture')
                if mode == 'provenance': archive.writestr('base/assets/info.txt', ''.join(['Generated by ', 'Chat', 'GPT']))
                if mode == 'private': archive.writestr('base/assets/upload-key.properties', 'secret')
            if mode != 'unsigned':
                run([JAVA / 'jarsigner', '-keystore', env['CM_KEYSTORE_PATH'], '-storepass:env', 'CM_KEYSTORE_PASSWORD',
                     '-keypass:env', 'CM_KEY_PASSWORD', bundle, 'test'], env)
            run(['python3', SCRIPTS / 'verify_aab.py', bundle], env, ok=mode in {'universal', 'four-abi'})
    run(['python3', SCRIPTS / 'audit_repository.py'])
    print('PASS: YAML/bash, signing bridge, Java Properties, SDK selection, AAB positive/negative fixtures, checkout audit')


if __name__ == '__main__':
    main()
